#!/usr/bin/env python3
"""Generates the guarded PRODUCTION step-0 files (prepared, never applied by this script):

  supabase/production/apply_0_tracking.sql     migration tracking (supabase_migrations.schema_migrations) with the 25
                                               migrations production already has, and app_secrets.deploy_env =
                                               'production'. Changes no app table, function, policy or row.
  supabase/production/rollback_0_tracking.sql  removes exactly that (refuses once a newer migration is recorded)

Each file is one transaction that refuses to run unless: the cluster is Classi production's, the public schema has
exactly the fingerprint recorded on 20/11/2026 (scripts/production/expected_<last>.txt, normalized function bodies:
production stripped "--" comments), RLS is on everywhere, and the tracking state is the expected "before" state.
The checks run again just before COMMIT. Usage: python3 scripts/production/gen_bootstrap.py
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
CLUSTER = "7692130048193495360"        # pg_control_system().system_identifier of classi (rfxhqcagdsuhkjzwbawx)
LAST = "20261027020000"
EXPECTED = open(os.path.join(HERE, f"expected_{LAST}.txt")).read().strip()

mig = sorted(f for f in os.listdir(os.path.join(REPO, "supabase", "migrations")) if f.endswith(".sql") and f[:14] <= LAST)
if len(mig) != 25:
    sys.exit(f"expected 25 migrations up to {LAST}, found {len(mig)}")
for f in mig:
    if not re.fullmatch(r"\d{14}_[a-z0-9_]+\.sql", f):
        sys.exit(f"unexpected migration file name: {f}")

sys.path.insert(0, HERE)
from fpexpr import FP  # noqa: E402  the fingerprint of scripts/production/fingerprint.sql as one SQL expression

def guard(stage: str, tracking: str) -> str:
    return f"""do $guard$
declare v_cluster text; v_fp text;
begin
  select system_identifier::text into v_cluster from pg_control_system();
  if v_cluster is distinct from '{CLUSTER}' then
    raise exception 'refusing ({stage}): this is not the Classi production database (cluster %)', v_cluster;
  end if;
  v_fp := {FP};
  if v_fp is distinct from $exp${EXPECTED}$exp$ then
    raise exception 'refusing ({stage}): the public schema is not the one recorded on 20/11/2026 (production must still be on main''s 25 migrations): %', v_fp;
  end if;
{tracking}
end $guard$;"""

BEFORE_APPLY = """  if exists (select 1 from pg_namespace where nspname = 'supabase_migrations') then
    raise exception 'refusing: migration tracking already exists';
  end if;
  if exists (select 1 from public.app_secrets where key = 'deploy_env') then
    raise exception 'refusing: an environment marker is already set';
  end if;"""
AFTER_APPLY = f"""  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception 'refusing: there is no migration tracking table (the tracking table does not hold the 25 migrations)';
  end if;
  if (select count(*) from supabase_migrations.schema_migrations) <> 25
     or (select max(version) from supabase_migrations.schema_migrations) <> '{LAST}' then
    raise exception 'refusing: the tracking table does not hold exactly the 25 production migrations';
  end if;
  if (select value from public.app_secrets where key = 'deploy_env') is distinct from 'production' then
    raise exception 'refusing: the environment marker is not production';
  end if;"""

rows = ",\n  ".join(f"('{f[:14]}', '{f[:-4]}')" for f in mig)
HEAD = """-- GENERATED by scripts/production/gen_bootstrap.py. Do not edit by hand.
-- Classi PRODUCTION, step 0 ({what}). Run ONCE in the Supabase SQL Editor of the production project, only with the
-- owner's approval and after a backup proven by restore. One transaction: any refusal or error changes nothing.
"""

apply_sql = HEAD.format(what="migration tracking and environment marker") + f"""begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
{guard("before", BEFORE_APPLY)}

create schema supabase_migrations;
revoke all on schema supabase_migrations from public;
create table supabase_migrations.schema_migrations (version text primary key, statements text[], name text);
revoke all on supabase_migrations.schema_migrations from public;
do $r$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then execute 'revoke all on schema supabase_migrations from anon, authenticated'; end if;
end $r$;
insert into supabase_migrations.schema_migrations (version, name) values
  {rows};
insert into public.app_secrets (key, value) values ('deploy_env', 'production');

{guard("before commit", AFTER_APPLY)}
commit;
"""

rollback_sql = HEAD.format(what="ROLLBACK of the tracking and marker") + f"""begin;
set local lock_timeout = '5s';
{guard("before", AFTER_APPLY)}

drop table supabase_migrations.schema_migrations;
drop schema supabase_migrations;
delete from public.app_secrets where key = 'deploy_env' and value = 'production';

{guard("before commit", BEFORE_APPLY)}
commit;
"""

out = os.path.join(REPO, "supabase", "production")
os.makedirs(out, exist_ok=True)
for name, text in (("apply_0_tracking.sql", apply_sql), ("rollback_0_tracking.sql", rollback_sql)):
    with open(os.path.join(out, name), "w") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(os.path.join(out, name), REPO))
